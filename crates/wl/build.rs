//! Generates the Rust side of the Wayland protocols in `protocols/` (each interface's
//! requests as methods, its events as an enum, its enums as constants), with a small XML
//! reader of our own: protocol files are plain elements and attributes.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = Path::new("protocols");
    println!("cargo:rerun-if-changed=protocols");
    let mut files: Vec<_> = std::fs::read_dir(dir)
        .expect("protocols/")
        .map(|e| e.expect("a protocol file").path())
        .filter(|p| p.extension().is_some_and(|e| e == "xml"))
        .collect();
    files.sort();
    let mut interfaces = Vec::new();
    for f in &files {
        let text = std::fs::read_to_string(f).expect("a protocol file");
        let root = parse(&text).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
        for i in root.children.iter().filter(|c| c.name == "interface") {
            interfaces.push(interface(i));
        }
    }
    let known: BTreeMap<String, ()> = interfaces.iter().map(|i| (i.name.clone(), ())).collect();
    let mut out = String::new();
    out.push_str("// Generated by build.rs from protocols/*.xml. Don't edit.\n\n");
    for i in &interfaces {
        emit(&mut out, i, &known);
    }
    // every interface, for objects the server makes (a new_id in an event names its interface)
    out.push_str(
        "/// Every interface this crate knows.\npub static ALL: &[&crate::Interface] = &[\n",
    );
    for i in &interfaces {
        let _ = writeln!(out, "    &{}::INTERFACE,", i.name);
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("protocols.rs");
    std::fs::write(dest, out).unwrap();
}

// ---- a small XML reader: elements, attributes, comments; text is skipped ----

#[derive(Debug, Default)]
struct Element {
    name: String,
    attrs: BTreeMap<String, String>,
    children: Vec<Element>,
}

fn parse(text: &str) -> Result<Element, String> {
    let b = text.as_bytes();
    let mut i = 0;
    let mut stack: Vec<Element> = vec![Element::default()];
    while i < b.len() {
        if b[i] != b'<' {
            i += 1;
            continue;
        }
        if text[i..].starts_with("<!--") {
            i += text[i..].find("-->").ok_or("an unclosed comment")? + 3;
            continue;
        }
        if text[i..].starts_with("<?") {
            i += text[i..].find("?>").ok_or("an unclosed declaration")? + 2;
            continue;
        }
        if text[i..].starts_with("<![CDATA[") {
            i += text[i..].find("]]>").ok_or("an unclosed CDATA")? + 3;
            continue;
        }
        if text[i..].starts_with("<!") {
            i += text[i..].find('>').ok_or("an unclosed doctype")? + 1;
            continue;
        }
        if text[i..].starts_with("</") {
            let end = i + text[i..].find('>').ok_or("an unclosed end tag")?;
            let name = text[i + 2..end].trim();
            let done = stack.pop().ok_or("too many end tags")?;
            if done.name != name {
                return Err(format!("</{name}> closes <{}>", done.name));
            }
            stack
                .last_mut()
                .ok_or("too many end tags")?
                .children
                .push(done);
            i = end + 1;
            continue;
        }
        // a start tag: name, attributes, maybe self-closing
        let mut j = i + 1;
        let mut quote = 0u8;
        while j < b.len() {
            match (quote, b[j]) {
                (0, b'"' | b'\'') => quote = b[j],
                (q, c) if q != 0 && c == q => quote = 0,
                (0, b'>') => break,
                _ => {}
            }
            j += 1;
        }
        if j >= b.len() {
            return Err("an unclosed tag".into());
        }
        let inner = &text[i + 1..j];
        let closed = inner.ends_with('/');
        let inner = inner.trim_end_matches('/');
        let mut el = Element::default();
        let name_end = inner
            .find(|c: char| c.is_whitespace())
            .unwrap_or(inner.len());
        el.name = inner[..name_end].to_string();
        el.attrs = attributes(&inner[name_end..])?;
        if closed {
            stack.last_mut().unwrap().children.push(el);
        } else {
            stack.push(el);
        }
        i = j + 1;
    }
    let mut top = stack.pop().ok_or("no document")?;
    if !stack.is_empty() {
        return Err(format!("<{}> is never closed", top.name));
    }
    top.children.retain(|c| c.name == "protocol");
    top.children.pop().ok_or_else(|| "no <protocol>".into())
}

fn attributes(s: &str) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut rest = s.trim();
    while !rest.is_empty() {
        let eq = rest
            .find('=')
            .ok_or_else(|| format!("an attribute without a value: {rest}"))?;
        let key = rest[..eq].trim().to_string();
        let after = rest[eq + 1..].trim_start();
        let q = after.chars().next().ok_or("an empty attribute")?;
        if q != '"' && q != '\'' {
            return Err(format!("an unquoted attribute: {key}"));
        }
        let end = after[1..].find(q).ok_or("an unclosed attribute")? + 1;
        out.insert(key, unescape(&after[1..end]));
        rest = after[end + 1..].trim_start();
    }
    Ok(out)
}

fn unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

// ---- the protocol model ----

struct Interface {
    name: String,
    version: u32,
    requests: Vec<Message>,
    events: Vec<Message>,
    enums: Vec<Enum>,
}

struct Message {
    name: String,
    destructor: bool,
    since: u32,
    args: Vec<ArgSpec>,
}

struct ArgSpec {
    name: String,
    kind: String,
    interface: Option<String>,
    nullable: bool,
}

struct Enum {
    name: String,
    entries: Vec<(String, u32)>,
}

fn interface(e: &Element) -> Interface {
    let msg = |m: &Element| Message {
        name: m.attrs["name"].clone(),
        destructor: m.attrs.get("type").is_some_and(|t| t == "destructor"),
        since: m.attrs.get("since").map_or(1, |s| s.parse().unwrap()),
        args: m
            .children
            .iter()
            .filter(|a| a.name == "arg")
            .map(|a| ArgSpec {
                name: a.attrs["name"].clone(),
                kind: a.attrs["type"].clone(),
                interface: a.attrs.get("interface").cloned(),
                nullable: a.attrs.get("allow-null").is_some_and(|v| v == "true"),
            })
            .collect(),
    };
    Interface {
        name: e.attrs["name"].clone(),
        version: e.attrs["version"].parse().unwrap(),
        requests: e
            .children
            .iter()
            .filter(|c| c.name == "request")
            .map(msg)
            .collect(),
        events: e
            .children
            .iter()
            .filter(|c| c.name == "event")
            .map(msg)
            .collect(),
        enums: e
            .children
            .iter()
            .filter(|c| c.name == "enum")
            .map(|en| Enum {
                name: en.attrs["name"].clone(),
                entries: en
                    .children
                    .iter()
                    .filter(|c| c.name == "entry")
                    .map(|c| {
                        let v = &c.attrs["value"];
                        let v = match v.strip_prefix("0x") {
                            Some(h) => u32::from_str_radix(h, 16).unwrap(),
                            None => v.parse().unwrap(),
                        };
                        (c.attrs["name"].clone(), v)
                    })
                    .collect(),
            })
            .collect(),
    }
}

// ---- writing Rust ----

fn camel(s: &str) -> String {
    s.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map_or(String::new(), |f| f.to_uppercase().chain(c).collect())
        })
        .collect()
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn ident(s: &str) -> String {
    if KEYWORDS.contains(&s) {
        format!("r#{s}")
    } else {
        s.to_string()
    }
}

fn konst(s: &str) -> String {
    let u = s.to_uppercase();
    if u.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{u}")
    } else {
        u
    }
}

fn kind_desc(a: &ArgSpec) -> String {
    let iface = |i: &Option<String>| match i {
        Some(n) => format!("Some(\"{n}\")"),
        None => "None".into(),
    };
    match a.kind.as_str() {
        "int" => "ArgKind::Int".into(),
        "uint" => "ArgKind::Uint".into(),
        "fixed" => "ArgKind::Fixed".into(),
        "string" => "ArgKind::Str".into(),
        "object" => format!("ArgKind::Object({})", iface(&a.interface)),
        "new_id" => format!("ArgKind::NewId({})", iface(&a.interface)),
        "array" => "ArgKind::Array".into(),
        "fd" => "ArgKind::Fd".into(),
        k => panic!("an unknown argument type {k}"),
    }
}

fn emit(out: &mut String, i: &Interface, known: &BTreeMap<String, ()>) {
    let ty = camel(&i.name);
    let typed = |n: &Option<String>| {
        n.as_ref()
            .filter(|n| known.contains_key(*n))
            .map(|n| format!("super::{n}::{}", camel(n)))
    };
    let _ = writeln!(out, "pub mod {} {{", i.name);
    let _ = writeln!(
        out,
        "    #![allow(unused, clippy::all, non_upper_case_globals)]"
    );
    let _ = writeln!(
        out,
        "    use crate::{{Arg, ArgKind, Connection, Id, Interface, MessageDesc, Proxy, Result, Error}};"
    );
    let _ = writeln!(out, "    use std::os::fd::{{BorrowedFd, OwnedFd}};");
    // descriptors
    let msgs = |list: &[Message]| -> String {
        list.iter()
            .map(|m| {
                let args: Vec<String> = m.args.iter().map(kind_desc).collect();
                format!(
                    "MessageDesc {{ name: \"{}\", since: {}, destructor: {}, args: &[{}] }}",
                    m.name,
                    m.since,
                    m.destructor,
                    args.join(", ")
                )
            })
            .collect::<Vec<_>>()
            .join(",\n        ")
    };
    let _ = writeln!(
        out,
        "    pub static INTERFACE: Interface = Interface {{\n        name: \"{}\",\n        version: {},\n        requests: &[\n        {}\n        ],\n        events: &[\n        {}\n        ],\n    }};",
        i.name,
        i.version,
        msgs(&i.requests),
        msgs(&i.events)
    );
    // the proxy
    let _ = writeln!(
        out,
        "    #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]"
    );
    let _ = writeln!(out, "    pub struct {ty}(pub Id);");
    let _ = writeln!(
        out,
        "    impl Proxy for {ty} {{\n        const INTERFACE: &'static Interface = &INTERFACE;\n        fn from_id(id: Id) -> Self {{ Self(id) }}\n        fn id(&self) -> Id {{ self.0 }}\n    }}"
    );
    // requests
    let _ = writeln!(out, "    impl {ty} {{");
    for (op, r) in i.requests.iter().enumerate() {
        let mut params = Vec::new();
        let mut args = Vec::new();
        let mut ret = "()".to_string();
        let mut generic = String::new();
        let mut pre = Vec::new();
        let mut result = "Ok(())".to_string();
        for a in &r.args {
            let n = ident(&a.name);
            match a.kind.as_str() {
                "int" => {
                    params.push(format!("{n}: i32"));
                    args.push(format!("Arg::Int({n})"));
                }
                "uint" => {
                    params.push(format!("{n}: u32"));
                    args.push(format!("Arg::Uint({n})"));
                }
                "fixed" => {
                    params.push(format!("{n}: f64"));
                    args.push(format!("Arg::Fixed(({n} * 256.0).round() as i32)"));
                }
                "string" => {
                    if a.nullable {
                        params.push(format!("{n}: Option<&str>"));
                        args.push(format!("Arg::Str({n}.map(str::to_string))"));
                    } else {
                        params.push(format!("{n}: &str"));
                        args.push(format!("Arg::Str(Some({n}.to_string()))"));
                    }
                }
                "object" => {
                    let t = typed(&a.interface);
                    match (t, a.nullable) {
                        (Some(t), false) => {
                            params.push(format!("{n}: {t}"));
                            args.push(format!("Arg::Object(Some({n}.0))"));
                        }
                        (Some(t), true) => {
                            params.push(format!("{n}: Option<{t}>"));
                            args.push(format!("Arg::Object({n}.map(|o| o.0))"));
                        }
                        (None, false) => {
                            params.push(format!("{n}: Id"));
                            args.push(format!("Arg::Object(Some({n}))"));
                        }
                        (None, true) => {
                            params.push(format!("{n}: Option<Id>"));
                            args.push(format!("Arg::Object({n})"));
                        }
                    }
                }
                "new_id" => match typed(&a.interface) {
                    Some(t) => {
                        let iface = a.interface.as_ref().unwrap();
                        pre.push(format!(
                            "let {n} = c.new_object(&super::{iface}::INTERFACE, c.version_of(self.0));"
                        ));
                        args.push(format!("Arg::NewId({n})"));
                        ret = t.clone();
                        result = format!("Ok({t}({n}))");
                    }
                    None => {
                        // untyped (wl_registry.bind): the caller says what it binds
                        generic = "<P: Proxy>".into();
                        params.push("version: u32".into());
                        pre.push(format!("let {n} = c.new_object(P::INTERFACE, version);"));
                        args.push(format!(
                            "Arg::UntypedNewId {{ interface: P::INTERFACE.name.to_string(), version, id: {n} }}"
                        ));
                        ret = "P".into();
                        result = format!("Ok(P::from_id({n}))");
                    }
                },
                "array" => {
                    params.push(format!("{n}: &[u8]"));
                    args.push(format!("Arg::Array({n}.to_vec())"));
                }
                "fd" => {
                    params.push(format!("{n}: BorrowedFd<'_>"));
                    args.push(format!("Arg::FdOut({n}.try_clone_to_owned()?)"));
                }
                _ => unreachable!(),
            }
        }
        let name = ident(&r.name);
        let ps = if params.is_empty() {
            String::new()
        } else {
            format!(", {}", params.join(", "))
        };
        let _ = writeln!(
            out,
            "        pub fn {name}{generic}(&self, c: &mut Connection{ps}) -> Result<{ret}> {{"
        );
        for p in pre {
            let _ = writeln!(out, "            {p}");
        }
        let _ = writeln!(
            out,
            "            c.send(self.0, {op}, vec![{}])?;",
            args.join(", ")
        );
        if r.destructor {
            let _ = writeln!(out, "            c.forget(self.0);");
        }
        let _ = writeln!(out, "            {result}");
        let _ = writeln!(out, "        }}");
    }
    let _ = writeln!(out, "    }}");
    // events
    let _ = writeln!(out, "    #[derive(Debug)]");
    let _ = writeln!(out, "    pub enum Event {{");
    for e in &i.events {
        let fields: Vec<String> = e
            .args
            .iter()
            .map(|a| {
                let t = match a.kind.as_str() {
                    "int" => "i32".to_string(),
                    "uint" => "u32".into(),
                    "fixed" => "f64".into(),
                    "string" => {
                        if a.nullable {
                            "Option<String>".into()
                        } else {
                            "String".into()
                        }
                    }
                    "object" => {
                        let t = typed(&a.interface).unwrap_or_else(|| "Id".into());
                        // (an object event argument can name one already gone: optional)
                        format!("Option<{t}>")
                    }
                    "new_id" => typed(&a.interface).unwrap_or_else(|| "Id".into()),
                    "array" => "Vec<u8>".into(),
                    "fd" => "OwnedFd".into(),
                    _ => unreachable!(),
                };
                format!("{}: {t}", ident(&a.name))
            })
            .collect();
        let _ = writeln!(
            out,
            "        {} {{ {} }},",
            camel(&e.name),
            fields.join(", ")
        );
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    impl Event {{");
    let _ = writeln!(
        out,
        "        pub fn parse(opcode: u16, args: Vec<Arg>) -> Result<Event> {{"
    );
    let _ = writeln!(out, "            let mut it = args.into_iter();");
    let _ = writeln!(out, "            match opcode {{");
    for (op, e) in i.events.iter().enumerate() {
        let mut fields = Vec::new();
        for a in &e.args {
            let n = ident(&a.name);
            let get = match a.kind.as_str() {
                "int" => "it.next().and_then(Arg::int)".to_string(),
                "uint" => "it.next().and_then(Arg::uint)".into(),
                "fixed" => "it.next().and_then(Arg::fixed)".into(),
                "string" => {
                    if a.nullable {
                        "it.next().and_then(Arg::string)".into()
                    } else {
                        "it.next().and_then(Arg::string).flatten()".into()
                    }
                }
                "object" => {
                    let wrap = typed(&a.interface)
                        .map_or(String::new(), |t| format!(".map(|o| o.map({t}))"));
                    format!("it.next().and_then(Arg::object){wrap}")
                }
                "new_id" => {
                    let wrap = typed(&a.interface).map_or(String::new(), |t| format!(".map({t})"));
                    format!("it.next().and_then(Arg::new_id){wrap}")
                }
                "array" => "it.next().and_then(Arg::array)".into(),
                "fd" => "it.next().and_then(Arg::fd)".into(),
                _ => unreachable!(),
            };
            fields.push(format!(
                "{n}: {get}.ok_or(Error::Protocol(\"{}.{}: argument {}\".into()))?",
                i.name, e.name, a.name
            ));
        }
        let _ = writeln!(
            out,
            "                {op} => Ok(Event::{} {{ {} }}),",
            camel(&e.name),
            fields.join(", ")
        );
    }
    let _ = writeln!(
        out,
        "                _ => Err(Error::Protocol(format!(\"{}: no event {{opcode}}\"))),",
        i.name
    );
    let _ = writeln!(out, "            }}\n        }}\n    }}");
    let _ = writeln!(
        out,
        "    impl crate::EventSet for Event {{\n        const INTERFACE: &'static Interface = &INTERFACE;\n        fn parse(opcode: u16, args: Vec<Arg>) -> Result<Self> {{ Event::parse(opcode, args) }}\n    }}"
    );
    // enums
    for en in &i.enums {
        for (n, v) in &en.entries {
            let _ = writeln!(
                out,
                "    pub const {}_{}: u32 = {v};",
                konst(&en.name),
                konst(n)
            );
        }
    }
    let _ = writeln!(out, "}}\n");
}
