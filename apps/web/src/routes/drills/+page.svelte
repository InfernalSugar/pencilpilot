<script lang="ts">
	import { onMount } from 'svelte';
	import Tile from '#lib/ui/Tile.svelte';
	import { drillsBySkill, loadDrillResults, seeded } from '#lib/drills.js';

	const groups = drillsBySkill();
	const total = groups.reduce((s, g) => s + g.drills.length, 0);
	/** Small fixed seed so the server and browser draw the same preview. */
	const preview = (generate: (r: () => number) => string, i: number) => generate(seeded(11 + i));

	let last = $state<Record<string, number>>({});
	onMount(() => {
		const map: Record<string, number> = {};
		for (const r of loadDrillResults()) map[r.id] = r.avg;
		last = map;
	});
</script>

<svelte:head><title>Drills · PencilPilot</title></svelte:head>

<div class="pp-page">
	<header class="intro">
		<span class="pp-eyebrow">Fundamentals</span>
		<h1>Drills</h1>
		<p>
			{total} short, scored exercises for the basics: lines, perspective, proportions, shapes and values.
			Every round is a fresh target, so you never run out.
		</p>
		<nav class="jump" aria-label="Skills">
			{#each groups as g (g.skill)}
				<a href="#skill-{g.skill}">{g.name} <span>{g.drills.length}</span></a>
			{/each}
		</nav>
	</header>

	{#each groups as g (g.skill)}
		<section class="group" aria-labelledby="skill-{g.skill}">
			<h2 id="skill-{g.skill}">{g.name} <span class="count">{g.drills.length}</span></h2>
			<ul class="pp-bento grid">
				{#each g.drills as d, i (d.id)}
					<li>
						<Tile href="/drills/{d.id}" label={d.name}>
							<div class="preview" aria-hidden="true">
								<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by drills.ts, no user input -->
								{@html preview(d.generate, i)}
							</div>
							<div class="text">
								<h3>{d.name}</h3>
								<p class="blurb">{d.blurb}</p>
							</div>
							<p class="meta">
								<span>{d.rounds} rounds</span>
								{#if d.secondsPerRound}<span>{d.secondsPerRound} s each</span>{/if}
								{#if d.blind}<span>Looking exercise</span>{/if}
								{#if d.creative}<span class="creative">Creative exercise</span>{/if}
								{#if last[d.id] !== undefined}
									<span class="last">Last {last[d.id].toFixed(1)}</span>
								{/if}
							</p>
						</Tile>
					</li>
				{/each}
			</ul>
		</section>
	{/each}
</div>

